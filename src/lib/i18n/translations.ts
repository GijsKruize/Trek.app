export type TranslationKey = keyof typeof nl;

export function t(locale: Locale, key: TranslationKey, vars?: Vars): string {
  const template = dictionaries[locale]?.[key] ?? dictionaries[DEFAULT_LOCALE][key];
  return fill(template, vars);
}

/** Build a translator bound to one locale, so call sites can write
 * `tr("nav.feed")` instead of repeating the locale every time. */
export function translator(locale: Locale): (key: TranslationKey, vars?: Vars) => string {
  return (key: TranslationKey, vars?: Vars) => t(locale, key, vars);
}

export function dateLocaleTag(locale: Locale): string {
  return locale === "en" ? "en-GB" : "nl-NL";
}
